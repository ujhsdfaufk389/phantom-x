// =============================================================================
// PHANTOM-X :: Phase 5 -- channel cipher self-test
// =============================================================================
// crypt_test.go -- Proves the Go keystream matches the C one.
//
// WHY THIS EXISTS
//     The encrypted-channel variant has two independent implementations of
//     the same keystream: one in C (px_crypt.c, in the payload) and one
//     in Go (crypt.go, in the server). They have to agree byte for byte
//     or the session does not start.
//
//     When they did not agree, the symptom was a session that opened,
//     exchanged HELLO and CAPS in the clear, and then went silent at the
//     first encrypted frame. That is a very expensive way to find out
//     that one line of a keystream generator was different.
//
//     This test pins the keystream to a known vector, so a disagreement
//     is a failing test rather than a mysterious timeout.
//
//     THE VECTOR
//     The expected bytes were produced by the C implementation and
//     pasted in. If the C implementation changes, the vector changes and
//     this test fails loudly -- which is the correct outcome, because the
//     payload and the server have to be rebuilt together anyway.
//
// RUN
//     go test -v -run TestKeystreamVector .
// =============================================================================

package main

import (
	"bytes"
	"testing"
)

// TestKeystreamVector pins the keystream.
//
// The expected output was generated by px_crypt.c with the default lab
// key. It is a regression guard, not a specification: the two
// implementations have to agree, and this is how that agreement is
// checked.
func TestKeystreamVector(t *testing.T) {
	key := []byte(DefaultChannelKey)

	// The outbound stream (seed 0x00), which is what the payload
	// encrypts with.
	out := NewKeystream(key, 0x00)
	got := make([]byte, 16)
	out.Apply(got)

	want := []byte{
		0x57, 0x02, 0x06, 0x5C, 0x82, 0x50, 0xE9, 0xE9,
		0xD9, 0xCE, 0xFA, 0x5D, 0x8A, 0x6B, 0xA6, 0x27,
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("outbound keystream mismatch\n  got  % X\n  want % X",
			got, want)
	}

	// The inbound stream (seed 0x5A), which is what the payload
	// decrypts with.
	in := NewKeystream(key, 0x5A)
	gotIn := make([]byte, 16)
	in.Apply(gotIn)

	wantIn := []byte{
		0xA6, 0x14, 0x47, 0x92, 0xE4, 0xEB, 0x26, 0x3C,
		0xF2, 0x9B, 0x80, 0x0B, 0x4D, 0x4A, 0x80, 0x5A,
	}
	if !bytes.Equal(gotIn, wantIn) {
		t.Fatalf("inbound keystream mismatch\n  got  % X\n  want % X",
			gotIn, wantIn)
	}
}

// TestKeystreamRoundTrip checks that encrypt then decrypt returns the
// original, which is the property the channel actually depends on.
func TestKeystreamRoundTrip(t *testing.T) {
	key := []byte(DefaultChannelKey)

	sender := NewKeystream(key, 0x00)
	receiver := NewKeystream(key, 0x00) // same direction, same key

	plain := []byte("HELLO|x64|1234|HOST")
	frame := sender.EncryptFrame(plain)

	// The ciphertext must not contain the plaintext.
	if bytes.Contains(frame, plain) {
		t.Fatal("the plaintext survived into the frame")
	}

	// The length prefix is in the clear, by design.
	if int(frame[0]) != len(plain) {
		t.Fatalf("length prefix is %d, expected %d", frame[0], len(plain))
	}

	// A receiver with the same direction decrypts it.
	out, _, err := receiver.DecryptFrame(frame)
	if err != nil {
		t.Fatalf("decrypt failed: %v", err)
	}
	if !bytes.Equal(out, plain) {
		t.Fatalf("round trip mismatch\n  got  %q\n  want %q", out, plain)
	}
}

// TestKeystreamDirectionsDiffer checks that the two directions do not
// share a keystream.
//
// If they did, a message in one direction could be replayed in the
// other. It also confirms that the seed actually changes the stream,
// which is what the server relies on when it mirrors the payload's
// seeds.
func TestKeystreamDirectionsDiffer(t *testing.T) {
	key := []byte(DefaultChannelKey)

	a := NewKeystream(key, 0x00)
	b := NewKeystream(key, 0x5A)

	sa := make([]byte, 32)
	sb := make([]byte, 32)
	a.Apply(sa)
	b.Apply(sb)

	if bytes.Equal(sa, sb) {
		t.Fatal("the two directions produced the same keystream")
	}
}
